CREATE TABLE events (
    "id" UUID PRIMARY KEY,
    "title" VARCHAR(255),
    "slug" VARCHAR(255),
    "summary" VARCHAR(500),
    "description" VARCHAR,
    "eventType" VARCHAR,
    "status" VARCHAR,
    "visibility" VARCHAR,
    "startAt" TIMESTAMP,
    "endAt" TIMESTAMP,
    "timezone" VARCHAR(100),
    "bannerImageUrl" VARCHAR(1000),
    "thumbnailImageUrl" VARCHAR(1000),
    "registrationStartAt" TIMESTAMP,
    "registrationEndAt" TIMESTAMP,
    "isFeatured" BOOLEAN,
    "isPublished" BOOLEAN,
    "createdBy" UUID,
    "deletedAt" TIMESTAMP,
    "createdAt" TIMESTAMP DEFAULT NOW(),
    "updatedAt" TIMESTAMP DEFAULT NOW(),
    CONSTRAINT "fk_events_createdBy" FOREIGN KEY ("createdBy") REFERENCES "users" ("id")
);
CREATE INDEX "idx_events_createdBy" ON "events" ("createdBy");
